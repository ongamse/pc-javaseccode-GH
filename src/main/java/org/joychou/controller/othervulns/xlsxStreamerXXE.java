/**
 * Desc:  xlsx-streamer xxe vuln code
 * Usage: xl/workbook.xml
 * Ref:   https://www.itread01.com/hkpcyyp.html
 * Fix:   update xlsx-streamer to 2.1.0 or above
 *
 * @author JoyChou @2019-09-05
 */
@Controller
@RequestMapping("xlsx-streamer")
public class xlsxStreamerXXE {


    @GetMapping("/upload")
    public String index() {
        return "xxe_upload"; // return xxe_upload.html page
    }


    @PostMapping("/readxlsx")
    public void xllx_streamer_xxe(MultipartFile file) throws IOException {
        byte[] content = file.getBytes();
        rejectDoctypeInXmlParts(content);
        StreamingReader.builder().open(new ByteArrayInputStream(content));
    }

    /**
     * xlsx-streamer 2.0.0 parses the XML parts of the workbook with entity resolution enabled.
     * Reject any XML part that declares a DOCTYPE (and therefore any entity) before it is opened.
     */
    private static void rejectDoctypeInXmlParts(byte[] content) throws IOException {
        SAXParserFactory spf = SAXParserFactory.newInstance();
        try {
            spf.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
            spf.setFeature("http://xml.org/sax/features/external-general-entities", false);
            spf.setFeature("http://xml.org/sax/features/external-parameter-entities", false);
        } catch (SAXException | ParserConfigurationException e) {
            throw new IOException("Unable to configure secure XML parser", e);
        }

        try (ZipInputStream zis = new ZipInputStream(new ByteArrayInputStream(content))) {
            ZipEntry entry;
            while ((entry = zis.getNextEntry()) != null) {
                String name = entry.getName().toLowerCase(Locale.ROOT);
                if (entry.isDirectory() || !(name.endsWith(".xml") || name.endsWith(".rels"))) {
                    continue;
                }
                InputStream noClose = new FilterInputStream(zis) {
                    @Override
                    public void close() {
                        // keep the enclosing zip stream open
                    }
                };
                try {
                    spf.newSAXParser().parse(noClose, new DefaultHandler());
                } catch (SAXException | ParserConfigurationException e) {
                    throw new IllegalArgumentException("Rejected XML part in uploaded file: " + entry.getName());
                }
            }
        }
    }


    public static void main(String[] args) throws Exception {
        StreamingReader.builder().open((new FileInputStream("poc.xlsx")));
    }
}
